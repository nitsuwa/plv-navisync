import { createRequire } from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
let chromium;
try { ({ chromium } = require('playwright')); }
catch { ({ chromium } = require(process.env.PLAYWRIGHT_MODULE || `${process.env.USERPROFILE}/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright`)); }
const out = 'docs/verification/event-3d-preview/evidence';
fs.mkdirSync(out, { recursive: true });
const report = { status: 'RUNNING', mode: 'isolated local fixtures; no live database writes', checks: [], pageErrors: [], externalRequests: [] };
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  await context.route('**/*', route => { const url = new URL(route.request().url()); if (url.hostname === 'localhost' || url.hostname === '127.0.0.1') return route.continue(); report.externalRequests.push(route.request().url()); return route.abort(); });
  const page = await context.newPage();
  page.on('pageerror', error => report.pageErrors.push(error.message));
  const fixtureUrl = 'http://127.0.0.1:5173/docs/verification/event-3d-preview/fixture/index.html';
  await page.goto(fixtureUrl);
  await page.waitForLoadState('networkidle');
  report.initialButtons = await page.getByRole('button').allTextContents();
  await page.screenshot({ path: `${out}/indoor-2d.png` });
  const transform = await page.getByTestId('event-canvas-content').getAttribute('style');
  await page.getByRole('button', { name: '3D preview', exact: true }).click();
  const preview = page.getByRole('region', { name: 'Event 3D preview' });
  await preview.locator('canvas').waitFor({ state: 'visible', timeout: 30000 });
  await page.waitForTimeout(1500);
  assert.equal(await preview.getByRole('listitem').count(), 15);
  await page.screenshot({ path: `${out}/indoor-3d-desktop.png` });
  report.checks.push('Indoor 3D renders all 14 event assets and the event label');
  const beforeZoom = await preview.locator('canvas').screenshot();
  await page.getByRole('button', { name: 'Zoom in in 3D', exact: true }).click();
  await page.waitForTimeout(500);
  const afterZoom = await preview.locator('canvas').screenshot();
  assert.notDeepEqual(beforeZoom, afterZoom);
  await page.getByRole('button', { name: 'Fit map in 3D' }).click();
  await page.getByRole('button', { name: 'Focus event items in 3D' }).click();
  report.checks.push('Zoom and fit/focus camera controls work');
  await page.getByRole('button', { name: '2D layout', exact: true }).click();
  assert.equal(await page.getByTestId('event-canvas-content').getAttribute('style'), transform);
  report.checks.push('Switching back preserves the 2D viewport');
  await page.getByRole('button', { name: 'Outdoor fixture', exact: true }).click();
  await page.getByRole('button', { name: '3D preview', exact: true }).click();
  await preview.locator('canvas').waitFor({ state: 'visible' });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${out}/outdoor-3d-desktop.png` });
  report.checks.push('Outdoor campus renders the same event additions');
  await page.getByRole('button', { name: 'Toggle admin review', exact: true }).click();
  await page.getByRole('button', { name: '3D preview', exact: true }).click();
  await preview.locator('canvas').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('button', { name: 'Save Draft', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Toggle feedback placement', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '3D preview', exact: true }).isDisabled(), true);
  assert.equal(await page.getByRole('button', { name: '2D layout', exact: true }).getAttribute('aria-pressed'), 'true');
  report.checks.push('Admin review is read-only and feedback placement forces 2D');
  await page.getByRole('button', { name: 'Toggle feedback placement', exact: true }).click();
  await page.getByRole('button', { name: 'Indoor fixture', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '3D preview', exact: true }).click();
  await preview.locator('canvas').waitFor({ state: 'visible' });
  await page.waitForTimeout(1000);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), true);
  await page.screenshot({ path: `${out}/admin-indoor-3d-mobile.png` });
  report.checks.push('Compact admin preview and camera controls fit a 390px viewport');
  await page.getByRole('button', { name: 'Toggle theme', exact: true }).click();
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${out}/admin-indoor-3d-dark.png` });
  await preview.locator('canvas').evaluate(canvas => canvas.dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
  await page.getByRole('button', { name: 'Return to 2D', exact: true }).waitFor();
  await page.screenshot({ path: `${out}/3d-fallback-mobile.png` });
  await page.getByRole('button', { name: 'Return to 2D', exact: true }).click();
  assert.equal(await page.locator('[data-testid="event-editor-workspace"] [data-event-item]').count(), 15);
  report.checks.push('Graphics context loss offers 2D with all plotted items preserved');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.evaluate(() => localStorage.clear());
  for (const scenario of ['tent', 'remote-stage']) {
    await page.goto(`${fixtureUrl}?case=${scenario}`);
    await page.waitForLoadState('networkidle');
    await page.getByRole('button', { name: '3D preview', exact: true }).click();
    await preview.locator('canvas').waitFor({ state: 'visible' });
    await page.waitForTimeout(800);
    await page.screenshot({ path: `${out}/${scenario}-focus.png` });
    report.checks.push(scenario === 'tent' ? 'Single tall indoor tent focus keeps its roof in frame' : 'Outdoor focus reaches an event far from base campus buildings');
  }
  await page.addInitScript(() => Object.defineProperty(window, 'WebGLRenderingContext', { value: undefined }));
  await page.goto(fixtureUrl);
  await page.getByRole('button', { name: '3D preview', exact: true }).click();
  await page.getByRole('button', { name: 'Return to 2D', exact: true }).click();
  assert.equal(await page.locator('[data-testid="event-editor-workspace"] [data-event-item]').count(), 15);
  report.checks.push('Unsupported graphics device preserves the layout and returns to 2D');
  assert.deepEqual(report.pageErrors, []);
  assert.equal(report.externalRequests.some(url => /supabase/.test(url)), false);
  report.status = 'PASS';
} catch(error) { report.status = 'FAIL'; report.error = error.stack; process.exitCode = 1; }
finally { await browser.close(); fs.writeFileSync(`${out}/browser-results.json`, JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2)); }
